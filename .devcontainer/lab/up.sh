#!/usr/bin/env bash
# Starts the BeziSync lab (ADR 0018) and prints how to sign in. The Codespaces lab runs it on
# every start; it works on any machine with Docker too:
#
#   bash .devcontainer/lab/up.sh
#
# Safe to run again. The first run writes .env with a random master key, admin password and team
# password (never the demo's fixed ones); later runs reuse them.
#
# Environment:
#   BEZISYNC_IMAGE / BEZISYNC_WEB_IMAGE   images to run (default: the published :latest)
#   LAB_URL     the address your browser uses, when it is neither a codespace nor localhost
#   LAB_BUILD   1: build the images from this checkout instead of pulling them
set -euo pipefail

LAB_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(cd "$LAB_DIR/../.." && pwd)"
ENV_FILE="$LAB_DIR/.env"
STATE_DIR="$LAB_DIR/.state"
PROJECT=bezisync-lab
PORT=8080

compose() {
  docker compose --project-name "$PROJECT" --env-file "$ENV_FILE" \
    -f "$ROOT/deploy/compose/docker-compose.yml" -f "$LAB_DIR/compose.yml" "$@"
}

rand() {
  head -c "$1" /dev/urandom | base64 | tr -d '\n/+=' | head -c "$2"
}

lab_url() {
  if [ -n "${LAB_URL:-}" ]; then
    echo "${LAB_URL%/}"
  elif [ -n "${CODESPACE_NAME:-}" ]; then
    echo "https://${CODESPACE_NAME}-${PORT}.${GITHUB_CODESPACES_PORT_FORWARDING_DOMAIN:-app.github.dev}"
  else
    echo "http://localhost:${PORT}"
  fi
}

if ! docker info >/dev/null 2>&1; then
  echo "Docker is not running. In a codespace it starts with the container: wait a moment and run this script again." >&2
  exit 1
fi

if [ ! -f "$ENV_FILE" ]; then
  # Data encrypted with a lost master key can't be read, so a lab whose .env is gone starts over.
  if [ -n "$(docker volume ls -q --filter "label=com.docker.compose.project=$PROJECT")" ]; then
    echo "Removing an earlier lab whose secrets are gone..."
    bash "$LAB_DIR/down.sh" >/dev/null
  fi
  (
    umask 077
    {
      echo "# Generated by up.sh for this lab only. Never commit it."
      echo "BEZISYNC_MASTER_KEY=$(head -c 32 /dev/urandom | base64 | tr -d '\n')"
      echo "BEZISYNC_ADMIN_PASSWORD=Lab-$(rand 24 16)"
      echo "LAB_TEAM_PASSWORD=Team-$(rand 24 16)"
    } >"$ENV_FILE"
  )
fi

mkdir -p "$STATE_DIR"

# The browser reaches the lab through the codespace's forwarded URL (or localhost, or LAB_URL).
URL="$(lab_url)"
if grep -q '^LAB_PUBLIC_URL=' "$ENV_FILE"; then
  sed -i.bak "s#^LAB_PUBLIC_URL=.*#LAB_PUBLIC_URL=${URL}#" "$ENV_FILE" && rm -f "$ENV_FILE.bak"
else
  echo "LAB_PUBLIC_URL=${URL}" >>"$ENV_FILE"
fi

if [ "${LAB_BUILD:-0}" = "1" ]; then
  echo "Building BeziSync from this checkout and starting the lab..."
  BUILD=(--build)
else
  echo "Starting the lab (the first start downloads the images, a few minutes)..."
  BUILD=(--no-build)
fi
status=0
compose up -d "${BUILD[@]}" --wait --wait-timeout 900 || status=$?

ADMIN_PASSWORD="$(grep '^BEZISYNC_ADMIN_PASSWORD=' "$ENV_FILE" | cut -d= -f2-)"
TEAM_PASSWORD="$(grep '^LAB_TEAM_PASSWORD=' "$ENV_FILE" | cut -d= -f2-)"

# The banner and the sign-in file hold passwords: private, and recreated so an old mode can't stay.
rm -f "$STATE_DIR/login.txt" "$STATE_DIR/banner.txt"
umask 077
printf 'URL=%s\nADMIN=admin@bezisync.local\nADMIN_PASSWORD=%s\nTEAM_PASSWORD=%s\n' "$URL" "$ADMIN_PASSWORD" "$TEAM_PASSWORD" >"$STATE_DIR/login.txt"
{
  echo
  if [ "$status" -eq 0 ]; then
    echo "BeziSync lab is ready."
  else
    echo "BeziSync lab did not start completely (see the messages above)."
    echo "  Retry:    bash .devcontainer/lab/up.sh"
    echo "  Logs:     docker compose -p $PROJECT logs --tail 100 migrate api controller"
    echo "  Report:   https://github.com/daun-gatal/bezisync/issues/new?labels=lab"
  fi
  echo "  Open:     $URL"
  echo "            (or the Ports tab > BeziSync > globe icon)"
  echo "  Sign in:  admin@bezisync.local / $ADMIN_PASSWORD"
  echo "  Team:     editor@, operator@ and viewer@bezisync.local / $TEAM_PASSWORD"
  echo "  Guide:    .devcontainer/lab/WELCOME.md"
  echo "  Done?     Delete the codespace at https://github.com/codespaces"
  echo
} | tee "$STATE_DIR/banner.txt"

exit "$status"
